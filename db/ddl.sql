-- =====================================================================
-- PontoZero | ddl.sql - Criação das tabelas, tipos e restrições
--
-- Banco: PostgreSQL 16 (usa UNIQUE NULLS NOT DISTINCT, do PG 15 em diante).
--
-- As 9 tabelas e os nomes de colunas seguem exatamente o DER da equipe:
-- EMPRESA, USUARIO, CATEGORIA, REGIAO, INDICADOR, ESTABELECIMENTO,
-- ANALISE, REGIAO_ANALISE e RELATORIO.
--
-- Toda restrição tem nome, para aparecer clara nas mensagens de erro:
--   pk_<tabela>          chave primária                (PRIMARY KEY)
--   fk_<tabela>_<alvo>   chave estrangeira             (FOREIGN KEY)
--   uq_<tabela>_<campo>  valor único                   (UNIQUE)
--   ck_<tabela>_<campo>  regra de domínio              (CHECK)
--   NOT NULL             campo obrigatório (na própria coluna)
--
-- Ordem de criação: primeiro as tabelas sem chave estrangeira, depois as
-- que dependem delas. Tudo roda numa transação: se algo falhar, nada fica
-- criado pela metade.
--
-- Como rodar num banco vazio:
--   psql -U pontozero -d pontozero -v ON_ERROR_STOP=1 -f db/ddl.sql
--   psql -U pontozero -d pontozero -v ON_ERROR_STOP=1 -f db/seed_dml.sql
-- No Docker, a imagem do banco roda este arquivo sozinha na primeira vez
-- que sobe com o volume vazio (ver db/Dockerfile).
-- =====================================================================

SET client_encoding = 'UTF8';

BEGIN;

-- ---------------------------------------------------------------------
-- EMPRESA: quem usa a plataforma para planejar a expansão
-- ---------------------------------------------------------------------
CREATE TABLE empresa (
    id_empresa  INT          GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(100) NOT NULL,
    cnpj        VARCHAR(14),                -- opcional; quando informado, só dígitos
    segmento    VARCHAR(100),               -- opcional; mesmo texto de categoria.nome

    CONSTRAINT pk_empresa          PRIMARY KEY (id_empresa),
    CONSTRAINT uq_empresa_cnpj     UNIQUE (cnpj),
    CONSTRAINT ck_empresa_nome     CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_empresa_cnpj     CHECK (cnpj ~ '^[0-9]{14}$'),
    CONSTRAINT ck_empresa_segmento CHECK (segmento IS NULL OR length(trim(segmento)) > 0)
);

-- ---------------------------------------------------------------------
-- USUARIO: cada usuário pertence a exatamente uma empresa (1,1)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario  INT          GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL,
    senha       VARCHAR(255) NOT NULL,      -- hash bcrypt, nunca a senha em texto
    perfil      VARCHAR(50)  NOT NULL DEFAULT 'analista',
    id_empresa  INT          NOT NULL,

    CONSTRAINT pk_usuario         PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuario_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_nome    CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_usuario_email   CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    -- só aceita hash bcrypt ($2a$, $2b$ ou $2y$, 60 caracteres):
    -- senha em texto puro é barrada pelo próprio banco
    CONSTRAINT ck_usuario_senha   CHECK (senha ~ '^\$2[aby]?\$[0-9]{2}\$' AND length(senha) >= 59),
    CONSTRAINT ck_usuario_perfil  CHECK (perfil IN ('admin', 'analista'))
);

-- E-mail único sem diferenciar maiúsculas de minúsculas (HU-001 RN03):
-- "Ana@X.com" e "ana@x.com" são o mesmo e-mail. Uma UNIQUE comum não
-- enxerga isso, por isso a unicidade é um índice único sobre lower(email).
CREATE UNIQUE INDEX uq_usuario_email ON usuario (lower(email));

-- ---------------------------------------------------------------------
-- CATEGORIA: segmento de negócio do estabelecimento (farmácia, padaria...)
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id_categoria INT          GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(100) NOT NULL,
    descricao    TEXT,

    CONSTRAINT pk_categoria      PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_nome UNIQUE (nome),
    CONSTRAINT ck_categoria_nome CHECK (length(trim(nome)) > 0)
);

-- ---------------------------------------------------------------------
-- REGIAO: recorte territorial analisado (no piloto, bairros do Recife)
-- ---------------------------------------------------------------------
CREATE TABLE regiao (
    id_regiao  INT          GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(100) NOT NULL,
    tipo       VARCHAR(50)  NOT NULL,       -- ex.: 'Bairro'
    cidade     VARCHAR(100) NOT NULL,
    estado     VARCHAR(2)   NOT NULL,       -- sigla da UF

    CONSTRAINT pk_regiao        PRIMARY KEY (id_regiao),
    -- o mesmo nome pode existir em outra cidade, mas não duas vezes na mesma
    CONSTRAINT uq_regiao_local  UNIQUE (nome, cidade, estado),
    CONSTRAINT ck_regiao_nome   CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_regiao_tipo   CHECK (length(trim(tipo)) > 0),
    CONSTRAINT ck_regiao_cidade CHECK (length(trim(cidade)) > 0),
    CONSTRAINT ck_regiao_estado CHECK (estado ~ '^[A-Z]{2}$')
);

-- ---------------------------------------------------------------------
-- INDICADOR: dado territorial de uma região, sempre com a sua fonte.
-- Fonte é obrigatória (HU-007: indicador sem fonte não pode ser exibido).
-- Data de referência pode ser nula quando a fonte não informa.
-- A densidade não é guardada: é calculada na view vw_indicador_completo.
-- ---------------------------------------------------------------------
CREATE TABLE indicador (
    id_indicador    INT            GENERATED BY DEFAULT AS IDENTITY,
    tipo            VARCHAR(50)    NOT NULL,
    valor           DECIMAL(15, 2) NOT NULL,
    data_referencia DATE,
    fonte           VARCHAR(100)   NOT NULL,
    id_regiao       INT            NOT NULL,

    CONSTRAINT pk_indicador        PRIMARY KEY (id_indicador),
    CONSTRAINT fk_indicador_regiao FOREIGN KEY (id_regiao)
        REFERENCES regiao (id_regiao) ON UPDATE CASCADE ON DELETE CASCADE,
    -- um só valor por região, tipo e data (NULLS NOT DISTINCT: duas linhas
    -- "sem data" para a mesma região e tipo também contam como repetidas)
    CONSTRAINT uq_indicador_regiao_tipo_data
        UNIQUE NULLS NOT DISTINCT (id_regiao, tipo, data_referencia),
    CONSTRAINT ck_indicador_tipo   CHECK (tipo IN ('populacao', 'domicilios',
                                                   'moradores_por_domicilio',
                                                   'renda_media_domiciliar', 'area_km2')),
    CONSTRAINT ck_indicador_valor  CHECK (valor >= 0),
    CONSTRAINT ck_indicador_fonte  CHECK (length(trim(fonte)) > 0),
    -- o Censo mais antigo usado é o de 2010; nada vem de antes de 1900
    CONSTRAINT ck_indicador_data   CHECK (data_referencia >= DATE '1900-01-01')
);

-- ---------------------------------------------------------------------
-- ESTABELECIMENTO: oferta comercial existente (concorrência)
-- ---------------------------------------------------------------------
CREATE TABLE estabelecimento (
    id_estabelecimento INT            GENERATED BY DEFAULT AS IDENTITY,
    nome               VARCHAR(100)   NOT NULL,
    latitude           DECIMAL(10, 6) NOT NULL,
    longitude          DECIMAL(10, 6) NOT NULL,
    endereco           VARCHAR(255),
    id_regiao          INT            NOT NULL,
    id_categoria       INT            NOT NULL,

    CONSTRAINT pk_estabelecimento           PRIMARY KEY (id_estabelecimento),
    CONSTRAINT fk_estabelecimento_regiao    FOREIGN KEY (id_regiao)
        REFERENCES regiao (id_regiao) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_estabelecimento_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_estabelecimento_nome      CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_estabelecimento_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_estabelecimento_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_estabelecimento_endereco  CHECK (endereco IS NULL OR length(trim(endereco)) > 0)
);

-- ---------------------------------------------------------------------
-- ANALISE: estudo salvo por uma empresa (1,1 empresa)
-- A regra "data_criacao não pode estar no futuro" depende do dia de hoje,
-- então fica num trigger (02_indices_e_regras.sql), não num CHECK.
-- ---------------------------------------------------------------------
CREATE TABLE analise (
    id_analise   INT          GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR(100) NOT NULL,
    data_criacao DATE         NOT NULL DEFAULT CURRENT_DATE,
    objetivo     TEXT,
    id_empresa   INT          NOT NULL,

    CONSTRAINT pk_analise         PRIMARY KEY (id_analise),
    CONSTRAINT fk_analise_empresa FOREIGN KEY (id_empresa)
        REFERENCES empresa (id_empresa) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_analise_nome    CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_analise_data    CHECK (data_criacao >= DATE '2020-01-01')
);

-- ---------------------------------------------------------------------
-- REGIAO_ANALISE: tabela associativa N:N entre ANALISE e REGIAO
-- A chave primária composta impede a mesma região duas vezes na análise.
-- ---------------------------------------------------------------------
CREATE TABLE regiao_analise (
    id_analise INT NOT NULL,
    id_regiao  INT NOT NULL,

    CONSTRAINT pk_regiao_analise         PRIMARY KEY (id_analise, id_regiao),
    CONSTRAINT fk_regiao_analise_analise FOREIGN KEY (id_analise)
        REFERENCES analise (id_analise) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_regiao_analise_regiao  FOREIGN KEY (id_regiao)
        REFERENCES regiao (id_regiao) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- RELATORIO: cada exportação gerada a partir de uma análise
-- ---------------------------------------------------------------------
CREATE TABLE relatorio (
    id_relatorio INT         GENERATED BY DEFAULT AS IDENTITY,
    data_geracao DATE        NOT NULL DEFAULT CURRENT_DATE,
    formato      VARCHAR(50) NOT NULL,
    id_analise   INT         NOT NULL,

    CONSTRAINT pk_relatorio         PRIMARY KEY (id_relatorio),
    CONSTRAINT fk_relatorio_analise FOREIGN KEY (id_analise)
        REFERENCES analise (id_analise) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT ck_relatorio_formato CHECK (formato IN ('PDF', 'CSV')),
    CONSTRAINT ck_relatorio_data    CHECK (data_geracao >= DATE '2020-01-01')
);

-- ---------------------------------------------------------------------
-- Documentação guardada no próprio banco (aparece no pgAdmin/DBeaver)
-- ---------------------------------------------------------------------
COMMENT ON TABLE empresa         IS 'Empresas que usam a plataforma para planejar a expansão';
COMMENT ON TABLE usuario         IS 'Usuários; cada um pertence a uma empresa. Senha guardada como hash bcrypt';
COMMENT ON TABLE categoria       IS 'Segmentos de negócio do piloto';
COMMENT ON TABLE regiao          IS 'Regiões analisáveis (bairros do Recife no piloto)';
COMMENT ON TABLE indicador       IS 'Indicadores territoriais com fonte e data de referência';
COMMENT ON TABLE estabelecimento IS 'Oferta comercial existente em cada região';
COMMENT ON TABLE analise         IS 'Análises salvas pelas empresas';
COMMENT ON TABLE regiao_analise  IS 'Regiões incluídas em cada análise (N:N)';
COMMENT ON TABLE relatorio       IS 'Exportações geradas a partir das análises';

COMMENT ON COLUMN empresa.cnpj              IS 'CNPJ só com os 14 dígitos, sem pontuação; opcional';
COMMENT ON COLUMN empresa.segmento          IS 'Segmento analisado pela empresa (mesmo texto de categoria.nome)';
COMMENT ON COLUMN usuario.senha             IS 'Hash bcrypt da senha; o CHECK recusa texto puro';
COMMENT ON COLUMN usuario.perfil            IS 'admin ou analista';
COMMENT ON COLUMN indicador.tipo            IS 'populacao, domicilios, moradores_por_domicilio, renda_media_domiciliar ou area_km2';
COMMENT ON COLUMN indicador.data_referencia IS 'Data a que o dado se refere; NULL quando a fonte não informa';
COMMENT ON COLUMN indicador.fonte           IS 'Origem do dado; obrigatória (HU-007)';
COMMENT ON COLUMN relatorio.formato         IS 'PDF ou CSV';

COMMIT;

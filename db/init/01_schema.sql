-- =====================================================================
-- PontoZero | 01 - Estrutura do banco (modelo lógico da equipe)
--
-- As 9 tabelas e os nomes de colunas seguem exatamente o DER da equipe:
-- EMPRESA, USUARIO, ANALISE, REGIAO_ANALISE, REGIAO, INDICADOR,
-- ESTABELECIMENTO, CATEGORIA e RELATORIO.
-- O que foi acrescentado aqui são só regras de integridade (NOT NULL,
-- UNIQUE, CHECK e ações das chaves estrangeiras), sem mudar o modelo.
--
-- Este arquivo roda sozinho na PRIMEIRA vez que o container do banco sobe
-- com o volume vazio (pasta /docker-entrypoint-initdb.d). Depois disso os
-- dados ficam no volume e o script não roda de novo.
-- =====================================================================

SET client_encoding = 'UTF8';

-- ---------------------------------------------------------------------
-- EMPRESA: quem usa a plataforma para planejar a expansão
-- ---------------------------------------------------------------------
CREATE TABLE empresa (
    id_empresa  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    cnpj        VARCHAR(14)  UNIQUE CHECK (cnpj ~ '^[0-9]{14}$'),
    segmento    VARCHAR(100)
);

-- ---------------------------------------------------------------------
-- USUARIO: cada usuário pertence a exatamente uma empresa (1,1)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    email       VARCHAR(100) NOT NULL CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    -- só aceita hash bcrypt: senha em texto puro é barrada pelo próprio banco
    senha       VARCHAR(255) NOT NULL CHECK (senha LIKE '$2%' AND length(senha) >= 59),
    perfil      VARCHAR(50)  NOT NULL DEFAULT 'analista' CHECK (perfil IN ('admin', 'analista')),
    id_empresa  INT NOT NULL REFERENCES empresa (id_empresa) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- CATEGORIA: segmento de negócio do estabelecimento (farmácia, padaria...)
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(100) NOT NULL UNIQUE,
    descricao    TEXT
);

-- ---------------------------------------------------------------------
-- REGIAO: recorte territorial analisado (no piloto, bairros do Recife)
-- ---------------------------------------------------------------------
CREATE TABLE regiao (
    id_regiao  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    tipo       VARCHAR(50)  NOT NULL,
    cidade     VARCHAR(100) NOT NULL,
    estado     VARCHAR(2)   NOT NULL CHECK (estado ~ '^[A-Z]{2}$'),
    UNIQUE (nome, cidade, estado)
);

-- ---------------------------------------------------------------------
-- INDICADOR: dado territorial de uma região, sempre com a sua fonte.
-- Fonte é obrigatória (HU-007: indicador sem fonte não pode ser exibido).
-- Data de referência pode ser nula quando a fonte não informa.
-- ---------------------------------------------------------------------
CREATE TABLE indicador (
    id_indicador    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(50)    NOT NULL,
    valor           DECIMAL(15, 2) NOT NULL CHECK (valor >= 0),
    data_referencia DATE,
    fonte           VARCHAR(100)   NOT NULL CHECK (length(trim(fonte)) > 0),
    id_regiao       INT NOT NULL REFERENCES regiao (id_regiao) ON DELETE CASCADE,
    UNIQUE NULLS NOT DISTINCT (id_regiao, tipo, data_referencia)
);

-- ---------------------------------------------------------------------
-- ESTABELECIMENTO: oferta comercial existente (concorrência)
-- ---------------------------------------------------------------------
CREATE TABLE estabelecimento (
    id_estabelecimento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(100)   NOT NULL,
    latitude           DECIMAL(10, 6) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude          DECIMAL(10, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    endereco           VARCHAR(255),
    id_regiao          INT NOT NULL REFERENCES regiao (id_regiao) ON DELETE CASCADE,
    id_categoria       INT NOT NULL REFERENCES categoria (id_categoria) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- ANALISE: estudo salvo por uma empresa (1,1 empresa)
-- ---------------------------------------------------------------------
CREATE TABLE analise (
    id_analise   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    data_criacao DATE NOT NULL DEFAULT CURRENT_DATE,
    objetivo     TEXT,
    id_categoria INT REFERENCES categoria (id_categoria) ON DELETE RESTRICT,
    versao_metodologia VARCHAR(30) NOT NULL DEFAULT 'legado',
    capturado_em TIMESTAMPTZ,
    snapshot     JSONB CONSTRAINT analise_snapshot_objeto CHECK (snapshot IS NULL OR jsonb_typeof(snapshot) = 'object'),
    id_empresa   INT NOT NULL REFERENCES empresa (id_empresa) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- REGIAO_ANALISE: tabela associativa N:N entre ANALISE e REGIAO
-- ---------------------------------------------------------------------
CREATE TABLE regiao_analise (
    id_analise INT NOT NULL REFERENCES analise (id_analise) ON DELETE CASCADE,
    id_regiao  INT NOT NULL REFERENCES regiao  (id_regiao)  ON DELETE RESTRICT,
    PRIMARY KEY (id_analise, id_regiao)
);

-- ---------------------------------------------------------------------
-- RELATORIO: cada exportação gerada a partir de uma análise
-- ---------------------------------------------------------------------
CREATE TABLE relatorio (
    id_relatorio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_geracao DATE NOT NULL DEFAULT CURRENT_DATE,
    formato      VARCHAR(50) NOT NULL CHECK (formato IN ('PDF', 'CSV')),
    id_analise   INT NOT NULL REFERENCES analise (id_analise) ON DELETE CASCADE
);

COMMENT ON TABLE empresa         IS 'Empresas que usam a plataforma para planejar a expansão';
COMMENT ON TABLE usuario         IS 'Usuários; cada um pertence a uma empresa. Senha guardada como hash bcrypt';
COMMENT ON TABLE categoria       IS 'Segmentos de negócio do piloto';
COMMENT ON TABLE regiao          IS 'Regiões analisáveis (bairros do Recife no piloto)';
COMMENT ON TABLE indicador       IS 'Indicadores territoriais com fonte e data de referência';
COMMENT ON TABLE analise         IS 'Análises salvas pelas empresas';
COMMENT ON TABLE regiao_analise  IS 'Regiões incluídas em cada análise (N:N)';
COMMENT ON TABLE relatorio       IS 'Exportações geradas a partir das análises';
